
namespace GameLibrary.Enums
{
    /// <summary>
    /// Определяет степень близости числа игрока к загаданному числу.
    /// </summary>
    public enum TemperatureHint
    {
        /// <summary>
        /// Предположение игрока находится далеко от загаданного числа.
        /// </summary>
        Cold,

        /// <summary>
        /// Предположение игрока находится на среднем расстоянии от загаданного числа.
        /// </summary>
        Warm,

        /// <summary>
        /// Предположение игрока находится близко к загаданному числу.
        /// </summary>
        Hot
    }
}
