namespace GameLibrary.Interfaces
{
    /// <summary>
    /// Представляет интерфейс уровня сложности игры.
    /// Определяет общие характеристики, которые должен предоставлять
    /// каждый уровень сложности: название, диапазон чисел
    /// и максимальное количество попыток.
    /// </summary>
    public interface IDifficulty
    {
        /// <summary>
        /// Возвращает название уровня сложности.
        /// </summary>
        string Name { get; }

        /// <summary>
        /// Возвращает минимальное число,
        /// которое может быть загадано в игре.
        /// </summary>
        int MinNumber { get; }

        /// <summary>
        /// Возвращает максимальное число,
        /// которое может быть загадано в игре.
        /// </summary>
        int MaxNumber { get; }

        /// <summary>
        /// Возвращает максимальное количество попыток,
        /// предоставляемых игроку на выбранном уровне сложности.
        /// </summary>
        int MaxAttempts { get; }
    }
}